/**
 * Persisted domain records. Every column of `migrations/*.sql` maps to one
 * field here (snake_case in SQL, camelCase here). Timestamps are ISO strings.
 */
import type {
  ChatAttachment,
  McpServer,
  Modality,
  TaskKind,
  TaskStatus,
  TextEffort,
  ToolDisplay,
  ToolTaskRef,
  TurnMode,
} from '@artemis/contracts/chat-types';

/* The LLM content shapes are stored as opaque JSON to keep storage independent of @artemis/llm. */
export type StoredContent = unknown[];
export type JsonValue = unknown;

export interface ConversationRecord {
  id: string;
  title: string | null;
  /** `auto`: generated by the title service; `user`: renamed by the user (wins). */
  titleSource: 'auto' | 'user' | null;
  createdAt: string;
  updatedAt: string;
  lastMessageAt: string | null;
  archivedAt: string | null;
  /** MCP qualified tool names last shown to the model (for reminder diffs after respawn). */
  mcpToolNamesShown: string[] | null;
}

/** System prompt + tool definitions frozen when a conversation (or task) is created. */
export interface PromptSnapshotRecord {
  id: string;
  ownerKind: 'conversation' | 'task';
  ownerId: string;
  systemPrompt: string;
  /** `ToolDefinition[]` in the exact order sent to the provider. */
  tools: JsonValue[];
  /** `system`, `agent:general-purpose`, `agent:research`, `title`. */
  templateId: string;
  /** sha256 of the template source the prompt was rendered from. */
  templateHash: string;
  createdAt: string;
}

export type TurnKind = 'user' | 'update';
export type TurnStatus = 'running' | 'completed' | 'failed' | 'cancelled';

export interface TurnUsage {
  inputTokens: number;
  outputTokens: number;
  cacheReadTokens: number;
  cacheWriteTokens: number;
  reasoningTokens: number;
  /** Model steps (requests) in the turn. */
  steps: number;
  /** Input tokens of the last request: the context size shown in the UI ring. */
  lastContextTokens: number;
}

/** What memory recall did before the answer (observability). */
export interface RecallTrace {
  budget: 'low' | 'mid' | 'high';
  query: string;
  memoryIds: string[];
  durationMs: number;
  error?: string;
}

export interface TurnRecord {
  id: string;
  conversationId: string;
  /** 1-based order within the conversation. */
  seq: number;
  kind: TurnKind;
  modality: Modality;
  mode: TurnMode;
  effort: TextEffort | null;
  status: TurnStatus;
  error: string | null;
  clientMessageId: string | null;
  model: string | null;
  usage: TurnUsage | null;
  recall: RecallTrace | null;
  startedAt: string;
  endedAt: string | null;
  /** Set once the turn was sent to long-term memory. */
  memoryRetentionId: string | null;
}

/** A finished task delivered inside a user-turn envelope. */
export interface DeliveredUpdate {
  id: string;
  taskId: string;
  title: string;
  status: 'completed' | 'failed' | 'cancelled';
  needsInput: boolean;
  report: string;
  durationMs?: number;
}

export interface RecalledMemory {
  id: string;
  text: string;
  type: 'world' | 'experience' | 'observation';
  /** occurred or mentioned date, ISO. */
  date?: string;
}

/**
 * Structured per-turn context of a user message (what the old base64
 * `[[app-envelope:v1]]` encoded). The exact text sent to the model lives in
 * `MessageRecord.content`; this is for the UI and for analytics.
 */
export interface UserTurnEnvelope {
  version: 2;
  mode: TurnMode;
  /** The user's own words ('' for update-only turns). */
  text: string;
  currentDateTime: string;
  attachments: ChatAttachment[];
  updates: DeliveredUpdate[];
  /** MCP reminder rendered into this turn, if any. */
  mcpReminder?: string;
  recalledMemories: RecalledMemory[];
  clientMessageId?: string;
}

export interface MessageRecord {
  id: string;
  conversationId: string;
  /** Set for a subagent task's own transcript; null for the conversation transcript. */
  taskId: string | null;
  turnId: string | null;
  /** Order within (conversationId, taskId). */
  seq: number;
  role: 'user' | 'assistant';
  /** Canonical LLM content blocks exactly as sent / received. */
  content: StoredContent;
  envelope: UserTurnEnvelope | null;
  provider: string | null;
  model: string | null;
  providerMessageId: string | null;
  stopReason: string | null;
  usage: JsonValue | null;
  /** `{startedAt, firstTokenMs, durationMs}` */
  timings: JsonValue | null;
  createdAt: string;
  deletedAt: string | null;
}

export type ToolCallStatus = 'running' | 'completed' | 'failed' | 'backgrounded' | 'cancelled';

export interface ToolCallRecord {
  /** Provider tool_use id. */
  id: string;
  conversationId: string;
  taskId: string | null;
  turnId: string | null;
  assistantMessageId: string;
  name: string;
  input: JsonValue;
  status: ToolCallStatus;
  /** Text the model received (bounded). */
  resultText: string | null;
  isError: boolean;
  display: ToolDisplay | null;
  taskRef: ToolTaskRef | null;
  startedAt: string;
  endedAt: string | null;
}

export interface TaskRecord {
  id: string;
  conversationId: string;
  kind: TaskKind;
  status: TaskStatus;
  title: string;
  /** Subagent: the assignment. */
  prompt: string | null;
  subagentType: string | null;
  /** Command task: the command line and its cwd. */
  command: string | null;
  cwd: string | null;
  exitCode: number | null;
  stdoutTail: string | null;
  stderrTail: string | null;
  outputPath: string | null;
  report: string | null;
  needsInput: boolean;
  /** Mode of the turn that started it (delivery policy). */
  originMode: TurnMode;
  originTurnId: string | null;
  originToolCallId: string | null;
  parentTaskId: string | null;
  resumedFromTaskId: string | null;
  /** 0 for user-started work; >0 when started while answering an update. */
  depth: number;
  model: string | null;
  usage: JsonValue | null;
  startedAt: string;
  endedAt: string | null;
  stopRequestedAt: string | null;
}

export type DeliveryState = 'held' | 'queued' | 'inflight' | 'delivered';

export interface BackgroundUpdateRecord {
  id: string;
  conversationId: string;
  taskId: string;
  title: string;
  status: 'completed' | 'failed' | 'cancelled';
  needsInput: boolean;
  report: string;
  durationMs: number | null;
  depth: number;
  delivery: DeliveryState;
  /** Present only while a text or voice turn owns the update. */
  deliveryToken: string | null;
  deliveryFrom: 'held' | 'queued' | null;
  deliveredTurnId: string | null;
  unread: boolean;
  createdAt: string;
  deliveredAt: string | null;
  readAt: string | null;
}

export interface McpSettingsRecord {
  servers: McpServer[];
  /** Entries that failed validation, kept for diagnostics. */
  invalidEntries: JsonValue[];
  revision: string;
  updatedAt: string;
}

export interface MemoryRetentionRecord {
  id: string;
  conversationId: string;
  turnIds: string[];
  /** Hindsight document id (`conversation:<id>`), appended to. */
  documentId: string;
  /** Idempotency key sent as Hindsight `operation_id`. */
  operationId: string;
  reason: 'batch' | 'flush';
  status: 'pending' | 'submitted' | 'failed';
  attempts: number;
  error: string | null;
  createdAt: string;
  submittedAt: string | null;
}

/** Keys of the `app_state` table. */
export type AppStateKey = 'last_active_conversation_id' | 'memory_bank_ready';
